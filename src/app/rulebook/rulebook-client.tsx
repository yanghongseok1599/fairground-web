function renderBlock(b: Block, i: number) {
  switch (b.k) {
    case "part":
      return (
        <div key={i} className="mt-12 mb-2 first:mt-0">
          <span
            className="inline-block rounded-md px-3 py-1.5 text-[13px] font-black tracking-wide"
            style={{ background: "var(--primary)", color: "#fff", fontFamily: "var(--font-body)" }}
          >
            {b.x}
          </span>
        </div>
      );
    case "ch":
      return (
        <h2
          key={i}
          className="mt-9 mb-3 border-b pb-2 text-[17px] font-black md:text-[19px]"
          style={{ color: "var(--color-fg-ink)", borderColor: "rgba(0,71,171,0.18)", fontFamily: "var(--font-body)" }}
        >
          {b.x}
        </h2>
      );
    case "sec":
      return (
        <h2
          key={i}
          className="mt-9 mb-3 text-[17px] font-black md:text-[19px]"
          style={{ color: "var(--primary)", fontFamily: "var(--font-body)" }}
        >
          {b.x}
        </h2>
      );
    case "art":
      return (
        <div key={i} className="mt-5">
          <h3 className="mb-2 flex flex-wrap items-baseline gap-2">
            <span className="fg-mono text-[13px]" style={{ color: "var(--primary)" }}>{b.no}</span>
            <span className="text-[15px] font-bold md:text-[16px]" style={{ color: "var(--color-fg-ink)", fontFamily: "var(--font-body)" }}>
              ({b.name})
            </span>
          </h3>
          {b.pre && (
            <p className="mb-2 text-[14px] leading-relaxed md:text-[15px]" style={{ color: "var(--color-fg-ink)", fontFamily: "var(--font-body)" }}>
              {b.pre}
            </p>
          )}
          {b.c && (
            <ul className="space-y-1.5 border-l-2 pl-4" style={{ borderColor: "rgba(0,71,171,0.14)" }}>
              {b.c.map((clause, ci) => (
                <li key={ci} className="text-[14px] leading-relaxed md:text-[15px]" style={{ color: "var(--color-fg-ink)", fontFamily: "var(--font-body)" }}>
                  <span className="mr-1.5" style={{ color: "var(--primary)" }}>{CIRCLED[ci] ?? `(${ci + 1})`}</span>
                  {clause}
                </li>
              ))}
            </ul>
          )}
          {b.b && (
            <ul className="mt-1 space-y-1.5 pl-1">
              {b.b.map((item, bi) => (
                <li key={bi} className="flex gap-2 text-[14px] leading-relaxed md:text-[15px]" style={{ color: "var(--color-fg-ink)", fontFamily: "var(--font-body)" }}>
                  <span style={{ color: "var(--primary)" }}>·</span>
                  <span>{item}</span>
                </li>
              ))}
            </ul>
          )}
        </div>
      );
    case "clauses":
      return (
        <ul key={i} className="space-y-1.5 border-l-2 pl-4" style={{ borderColor: "rgba(0,71,171,0.14)" }}>
          {b.c.map((clause, ci) => (
            <li key={ci} className="text-[14px] leading-relaxed md:text-[15px]" style={{ color: "var(--color-fg-ink)", fontFamily: "var(--font-body)" }}>
              <span className="mr-1.5" style={{ color: "var(--primary)" }}>{CIRCLED[ci] ?? `(${ci + 1})`}</span>
              {clause}
            </li>
          ))}
        </ul>
      );
    case "ul":
      return (
        <div key={i} className="mt-3">
          {b.title && (
            <p className="mb-1.5 text-[14px] font-bold md:text-[15px]" style={{ color: "var(--color-fg-ink)", fontFamily: "var(--font-body)" }}>
              {b.title}
            </p>
          )}
          <ul className="space-y-1.5 pl-1">
            {b.items.map((item, ii) => (
              <li key={ii} className="flex gap-2 text-[14px] leading-relaxed md:text-[15px]" style={{ color: "var(--color-fg-ink)", fontFamily: "var(--font-body)" }}>
                <span style={{ color: "var(--primary)" }}>·</span>
                <span>{item}</span>
              </li>
            ))}
          </ul>
        </div>
      );
    case "p":
      return (
        <p key={i} className="mt-3 text-[14px] leading-relaxed md:text-[15px]" style={{ color: "var(--color-fg-ink)", fontFamily: "var(--font-body)" }}>
          {b.x}
        </p>
      );
    case "tbl":
      return (
        <div key={i} className="mt-3 overflow-x-auto">
          <table className="w-full border-collapse text-[13px] md:text-[14px]">
            <thead>
              <tr>
                {b.h.map((head, hi) => (
                  <th
                    key={hi}
                    className="border px-3 py-2 text-left font-bold"
                    style={{ borderColor: "var(--color-fg-line-soft)", background: "var(--color-fg-paper-2)", color: "var(--color-fg-ink)" }}
                  >
                    {head}
                  </th>
                ))}
              </tr>
            </thead>
            <tbody>
              {b.r.map((row, ri) => (
                <tr key={ri}>
                  {row.map((cell, cii) => (
                    <td
                      key={cii}
                      className="border px-3 py-2 align-top"
                      style={{ borderColor: "var(--color-fg-line-soft)", color: "var(--color-fg-ink)" }}
                    >
                      {cell}
                    </td>
                  ))}
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      );
    case "note":
      return (
        <div
          key={i}
          className="mt-4 rounded-xl px-4 py-3 text-[13px] leading-relaxed md:text-[14px]"
          style={{ background: "var(--color-fg-paper-2)", border: "1px solid var(--color-fg-line-soft)", color: "var(--color-fg-ink-muted)", fontFamily: "var(--font-body)" }}
        >
          {b.x}
        </div>
      );
  }
}

