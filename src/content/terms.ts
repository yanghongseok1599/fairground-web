/**
 * 이용약관 골격.
 *
 * 뼈대: 공정위 전자상거래 표준약관 제10023호. 다만 이 표준약관은 2014년 게시본이라
 * 이후 생긴 두 규정이 없다 — 디지털콘텐츠 시험사용 의무(전자상거래법 제17조⑥, 2016)와
 * 해지를 가입보다 어렵게 만드는 다크패턴 금지(제21조의2). 아래 골격은 둘을 넣었다.
 *
 * 약관법 제3조: 한글로 쓰고 중요 내용은 눈에 띄게 하며, 요청하면 사본을 준다.
 * 이를 지키지 않으면 그 조항을 계약 내용으로 주장할 수 없다 (제3조④).
 * → 환불·책임 제한·자동결제 조항은 화면에서 굵게 강조할 것.
 *
 * 조사한 7개 중 페어그라운드·썸머인망상은 약관이 아예 없었다. 오토사장·트레이너마일스톤이
 * 가장 길었지만 회원이 약관에 동의하는 절차가 없었다 (오토사장).
 */
import type { LegalSection } from "@/lib/legal-document";

export interface TermsConfig {
  serviceName: string;
  /** 유료 판매가 없으면 false. 결제·환불 조항이 빠진다. */
  sellsOnline: boolean;
  /** 정기결제가 있으면 금액·주기·결제일·해지 방법을 명시하는 조항이 들어간다. */
  hasSubscription: boolean;
  /** 이용자가 글·사진을 올리는 기능이 있으면 게시물 조항이 들어간다. */
  hasUserContent: boolean;
  jurisdiction: string | null; // 관할 법원. null 이면 민사소송법에 따른다고 적는다.
}

export function termsSections(c: TermsConfig): LegalSection[] {
  const s: LegalSection[] = [
    { heading: "제1조 목적", body: [`이 약관은 ${c.serviceName}(이하 "서비스")의 이용 조건과 절차, 회사와 회원의 권리·의무를 정합니다.`] },
    { heading: "제2조 약관의 게시와 변경", body: [
      "회사는 이 약관을 서비스 초기화면에 게시합니다.",
      "약관을 바꿀 때는 적용일 7일 전부터, 회원에게 불리한 변경은 30일 전부터 공지하고 개별 통지합니다.",
      "회원은 변경된 약관에 동의하지 않으면 탈퇴할 수 있습니다.",
    ] },
    { heading: "제3조 회원가입과 탈퇴", body: [
      "이용자는 약관과 개인정보 수집·이용에 동의하고 회사가 정한 절차로 가입합니다.",
      "만 14세 미만은 가입할 수 없습니다.",
      "회원은 언제든지 마이페이지에서 직접 탈퇴할 수 있습니다. 탈퇴 절차는 가입 절차보다 복잡하지 않습니다.",
      "법령에 따라 보관해야 하는 거래 기록은 탈퇴 후에도 정해진 기간 동안 분리 보관합니다.",
    ] },
    { heading: "제4조 회원의 의무", body: [
      "회원은 자신의 계정과 비밀번호를 관리할 책임이 있으며 이를 제3자에게 이용하게 해서는 안 됩니다.",
      "타인의 정보 도용, 서비스 운영 방해, 법령 위반 행위를 해서는 안 됩니다.",
    ] },
    { heading: "제5조 서비스 이용 제한", body: [
      "회사는 회원이 제4조를 위반하면 사전 통지 후 이용을 제한할 수 있습니다. 긴급한 경우에는 사후에 통지합니다.",
      "회원은 이용 제한에 대해 이의를 신청할 수 있습니다.",
    ] },
  ];

  if (c.sellsOnline) {
    s.push(
      { heading: "제6조 계약의 성립과 결제", body: [
        "회원이 결제를 완료하고 회사가 승낙을 통지하면 계약이 성립합니다.",
        "회사는 결제 전에 상품·서비스의 내용, 가격, 청약철회 조건을 알립니다.",
      ] },
      { heading: "제7조 청약철회와 환불", body: [
        "청약철회와 환불은 별도의 환불정책에 따릅니다. 환불정책은 전자상거래법이 정한 기준보다 회원에게 불리하게 정하지 않습니다.",
      ] },
    );
  }
  if (c.hasSubscription) {
    s.push({ heading: "제8조 정기결제", body: [
      "정기결제는 신청 화면에 표시된 금액, 결제 주기, 결제일에 자동으로 청구됩니다.",
      "회원은 다음 결제일 전까지 마이페이지에서 언제든 해지할 수 있으며, 해지 후에는 다음 결제가 청구되지 않습니다.",
    ] });
  }
  if (c.hasUserContent) {
    s.push({ heading: "게시물", body: [
      "회원이 올린 게시물의 저작권은 회원에게 있습니다.",
      "회사는 서비스 운영과 홍보에 필요한 범위에서 게시물을 이용할 수 있으며, 회원은 언제든 게시물을 삭제할 수 있습니다.",
      "타인의 권리를 침해하거나 법령에 위반되는 게시물은 사전 통지 없이 게시를 중단할 수 있습니다.",
    ] });
  }
  s.push(
    { heading: "책임의 제한", body: [
      "회사는 천재지변 등 불가항력으로 서비스를 제공할 수 없는 경우 책임을 지지 않습니다.",
      "다만 회사의 고의 또는 중대한 과실로 인한 손해는 이 조항으로 면제되지 않습니다.",
    ] },
    { heading: "분쟁 해결과 관할", body: [
      "서비스 이용과 관련한 분쟁은 상호 협의로 해결하도록 노력합니다.",
      c.jurisdiction ? `소송은 ${c.jurisdiction}을 관할 법원으로 합니다.` : "소송이 제기되면 민사소송법에 따른 관할 법원에서 다툽니다.",
    ] },
  );
  return s;
}

